import fs from "node:fs";
import path from "node:path";

const workspaceRoot = path.resolve(process.cwd(), "..", "..");
const localNodeModules = path.resolve(process.cwd(), "node_modules");
const hoistedNodeModules = path.resolve(workspaceRoot, "node_modules");

if (fs.existsSync(localNodeModules)) {
  process.exit(0);
}

if (!fs.existsSync(hoistedNodeModules)) {
  console.error(`Cannot find hoisted node_modules at ${hoistedNodeModules}`);
  process.exit(1);
}

const relativeTarget = path.relative(path.dirname(localNodeModules), hoistedNodeModules);
fs.symlinkSync(relativeTarget, localNodeModules, "dir");
console.log(`Linked ${localNodeModules} -> ${relativeTarget}`);
